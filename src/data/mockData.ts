// Historical Trends Data for 30 Days (Daily readings)
export const GENERATE_DAILY_TRENDS = () => {
  const trends = [];
  const now = new Date();

  for (let i = 29; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const dayStr = d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    const isWeekend = d.getDay() === 0 || d.getDay() === 6;

    // Realistic variability: lower on weekends, realistic weekday consumption
    const elecBase = isWeekend ? 680 : 1220;
    const waterBase = isWeekend ? 9400 : 18200;
    const paperBase = isWeekend ? 400 : 2350;

    const noise = Math.sin(i) * 50;
    const elec = Math.round(elecBase + noise + (i === 0 ? 30 : 0));
    const water = Math.round(waterBase + noise * 12);
    const paper = Math.round(paperBase + noise * 3);

    // Baseline comparison
    const elecTarget = isWeekend ? 650 : 1100;
    const waterTarget = isWeekend ? 9000 : 16500;
    const paperTarget = isWeekend ? 350 : 1900;

    trends.push({
      date: dayStr,
      fullDate: d.toISOString().split('T')[0],
      electricity: elec,
      electricityBaseline: elecTarget,
      water: water,
      waterBaseline: waterTarget,
      paper: paper,
      paperBaseline: paperTarget,
      costINR: Math.round(elec * 8.5 + water * 0.05 + paper * 0.8),
      wasteINR: Math.max(0, Math.round((elec - elecTarget) * 8.5 + (water - waterTarget) * 0.05 + (paper - paperTarget) * 0.8)),
    });
  }
  return trends;
};

